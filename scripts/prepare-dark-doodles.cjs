// Run after changing artwork or cleanup masks. Guests receive regular PNGs,
// never canvases; original light-theme artwork is left untouched.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const { PNG } = require('pngjs');
function load(file) {
  const module = { exports: {} };
  vm.runInNewContext(ts.transpileModule(fs.readFileSync(file, 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.CommonJS },
  }).outputText, { module, exports: module.exports });
  return module.exports;
}
const { removeDoodlePaper, defringeDoodle, cleanDoodleHair } = load('lib/doodle-paper.ts');
const { doodleGapSeeds, doodleBottomCrops, doodleHairZones } = load('lib/doodle-cleanup.ts');
const directory = 'public/images/dark';
fs.mkdirSync(directory, { recursive: true });
const mapping = {};
function resize(source, maxEdge) {
  const ratio = Math.min(1, maxEdge / Math.max(source.width, source.height));
  if (ratio === 1) return source;
  const target = new PNG({ width: Math.round(source.width * ratio), height: Math.round(source.height * ratio) });
  for (let y = 0; y < target.height; y++) for (let x = 0; x < target.width; x++) {
    const sx = Math.max(0, (x + .5) * source.width / target.width - .5);
    const sy = Math.max(0, (y + .5) * source.height / target.height - .5);
    const x0 = Math.floor(sx), y0 = Math.floor(sy);
    const x1 = Math.min(x0 + 1, source.width - 1), y1 = Math.min(y0 + 1, source.height - 1);
    const fx = sx - x0, fy = sy - y0;
    for (let channel = 0; channel < 4; channel++) {
      const top = source.data[(y0 * source.width + x0) * 4 + channel] * (1 - fx) + source.data[(y0 * source.width + x1) * 4 + channel] * fx;
      const bottom = source.data[(y1 * source.width + x0) * 4 + channel] * (1 - fx) + source.data[(y1 * source.width + x1) * 4 + channel] * fx;
      target.data[(y * target.width + x) * 4 + channel] = Math.round(top * (1 - fy) + bottom * fy);
    }
  }
  return target;
}
for (const name of [...Object.keys(doodleGapSeeds), 'gurkireet-rings.png']) {
  const png = resize(PNG.sync.read(fs.readFileSync(path.join('public/images', name))), name === 'gurkireet-rings.png' ? 160 : 1200);
  removeDoodlePaper(png.data, png.width, png.height, doodleGapSeeds[name], doodleBottomCrops[name]);
  defringeDoodle(png.data, png.width, png.height);
  cleanDoodleHair(png.data, png.width, png.height, doodleHairZones[name]);
  // Versioned filenames prevent stale artwork after deployment.
  const output = name.replace('.png', '-v1.png');
  fs.writeFileSync(path.join(directory, output), PNG.sync.write(png));
  mapping['/images/' + name] = '/images/dark/' + output;
  console.log(output);
}
fs.writeFileSync('lib/dark-doodles.ts', '// Generated by npm run prepare:doodles.\nexport const darkDoodles: Record<string, string> = ' + JSON.stringify(mapping, null, 2) + ';\n');
